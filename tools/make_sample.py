    총 = sum(몫)
    결과, 남은 = [], 목표
    for i, w in enumerate(몫):
        v = max(3_000, 남은) if i == 건수 - 1 else \
            max(3_000, min(int(round(목표 * w / 총 / 100) * 100), 남은 - 3_000 * (건수 - i - 1)))
        남은 -= v
        결과.append((날(월, RNG.randint(1, 28)), RNG.choice(가맹점들), v))
    return 결과


